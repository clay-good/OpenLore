import { describe, it, expect, afterEach, vi } from 'vitest';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, readFileSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';

const verify = vi.hoisted(() => ({ result: {} as Record<string, unknown> }));
vi.mock('../../core/services/mcp-handlers/verify-change.js', async () => {
  const { logger } = await import('../../utils/logger.js');
  return {
    // The real handler logs through the shared logger; a hook must keep that off stdout.
    handleVerifyChange: vi.fn(async () => { logger.success('Successfully validated directory'); return verify.result; }),
  };
});

import { runHook, parseHookPayload, repoPath, renderReceipt } from './hook.js';

const dirs: string[] = [];
afterEach(() => { for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); });

const GIT_ENV = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null', GIT_AUTHOR_NAME: 'T', GIT_AUTHOR_EMAIL: 't@e', GIT_COMMITTER_NAME: 'T', GIT_COMMITTER_EMAIL: 't@e' };
function write(root: string, rel: string, content: string): void {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), content);
}
/** A git repository with OpenLore set up (an `.openlore` directory) and one commit. */
function repo(files: Record<string, string> = {}): string {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'olhook-')));
  dirs.push(root);
  mkdirSync(join(root, '.openlore'));
  for (const [rel, c] of Object.entries({ 'README.md': '# x\n', ...files })) write(root, rel, c);
  execFileSync('git', ['init', '-q', '-b', 'main'], { cwd: root, env: GIT_ENV });
  execFileSync('git', ['add', '-A'], { cwd: root, env: GIT_ENV });
  execFileSync('git', ['commit', '-qm', 'init'], { cwd: root, env: GIT_ENV });
  return root;
}
const payload = (root: string, file?: string, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ session_id: 's1', cwd: root, tool_name: 'Edit', ...(file ? { tool_input: { file_path: join(root, file) } } : {}), ...extra });
const context = (stdout: string) => (stdout ? (JSON.parse(stdout) as { hookSpecificOutput: { hookEventName: string; additionalContext: string } }).hookSpecificOutput : undefined);

const GENERATED = '// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: order.proto\npackage gen\n';

describe('payload and paths', () => {
  it('reads the fields the hooks use', () => {
    expect(parseHookPayload(JSON.stringify({ session_id: 'a', cwd: '/r', tool_name: 'Write', tool_input: { file_path: '/r/x.ts' }, stop_hook_active: true })))
      .toEqual({ sessionId: 'a', cwd: '/r', toolName: 'Write', files: ['/r/x.ts'], stopHookActive: true });
    expect(parseHookPayload('not json')).toEqual({ files: [], stopHookActive: false });
  });

  it('confines paths to the repository and accepts a file not written yet', () => {
    const root = repo();
    expect(repoPath(root, join(root, 'src/new/file.ts'))).toBe('src/new/file.ts');
    expect(repoPath(root, '/etc/passwd')).toBeUndefined();
    expect(repoPath(root, join(root, '..', 'x.ts'))).toBeUndefined();
  });

  it('keeps the most severe facts within the budget and counts the rest', () => {
    const items = Array.from({ length: 20 }, (_, i) => ({ key: `k${i}`, severity: i === 19 ? 'error' : 'info', text: 'x'.repeat(80) }));
    const out = renderReceipt('after-tools', items, 400)!;
    expect(out.split('\n')[1]).toContain('x'); // the error sorts first
    expect(out).toMatch(/\d+ more fact\(s\) not shown \(budget\)\./);
    expect(renderReceipt('after-tools', [])).toBeNull();
  });
});

describe('before-edit', () => {
  it('names a generated target before the write, and writes nothing to it', async () => {
    const root = repo({ 'gen/order.pb.go': GENERATED });
    const r = await runHook('before-edit', payload(root, 'gen/order.pb.go'));
    expect(r.exitCode).toBe(0);
    const c = context(r.stdout)!;
    expect(c.hookEventName).toBe('PreToolUse');
    expect(c.additionalContext).toContain('gen/order.pb.go is generated');
    expect(c.additionalContext).toContain('order.proto');
    expect(readFileSync(join(root, 'gen/order.pb.go'), 'utf-8')).toBe(GENERATED);
  });

  it('prints nothing for an ordinary file, outside an OpenLore repository, or when turned off', async () => {
    const root = repo({ 'src/a.ts': 'export const a = 1;\n', 'gen/order.pb.go': GENERATED });
    expect((await runHook('before-edit', payload(root, 'src/a.ts'))).stdout).toBe('');
    rmSync(join(root, '.openlore'), { recursive: true });
    expect((await runHook('before-edit', payload(root, 'gen/order.pb.go'))).stdout).toBe('');
    mkdirSync(join(root, '.openlore'));
    writeFileSync(join(root, '.openlore', 'config.json'), JSON.stringify({ hooks: { 'before-edit': false } }));
    expect((await runHook('before-edit', payload(root, 'gen/order.pb.go'))).stdout).toBe('');
  });

  it('states a fact once per harness session', async () => {
    const root = repo({ 'gen/order.pb.go': GENERATED });
    expect((await runHook('before-edit', payload(root, 'gen/order.pb.go'))).stdout).not.toBe('');
    expect((await runHook('before-edit', payload(root, 'gen/order.pb.go'))).stdout).toBe('');
    expect((await runHook('before-edit', payload(root, 'gen/order.pb.go', { session_id: 's2' }))).stdout).not.toBe('');
    const noSession = JSON.stringify({ cwd: root, tool_input: { file_path: join(root, 'gen/order.pb.go') } });
    expect((await runHook('before-edit', noSession)).stdout).not.toBe('');
    expect((await runHook('before-edit', noSession)).stdout).not.toBe('');
  });
});

describe('after-tools', () => {
  const TEST = "import { f } from './f';\nit('a', () => { expect(f()).toBe(1); });\nit('b', () => { expect(f()).toBe(2); });\n";

  it('records the agent\'s edit for the session ledger and states a weakened test once', async () => {
    const root = repo({ 'src/f.ts': 'export function f() { return 1; }\n', 'src/f.test.ts': TEST });
    write(root, 'src/f.test.ts', TEST.replace("it('b'", "it.skip('b'"));
    const r = await runHook('after-tools', payload(root, 'src/f.test.ts'));
    const c = context(r.stdout)!;
    expect(c.hookEventName).toBe('PostToolUse');
    expect(c.additionalContext).toContain('`it.skip` was added to test `b`');
    const log = readFileSync(join(root, '.openlore', 'session-ledger', 'agent-edits.jsonl'), 'utf-8');
    expect(JSON.parse(log.trim())).toMatchObject({ file: 'src/f.test.ts' });
    expect((await runHook('after-tools', payload(root, 'src/f.test.ts'))).stdout).toBe('');
  });

  it('states an import of something that does not exist', async () => {
    const root = repo({ 'src/f.ts': 'export function f() { return 1; }\n', 'src/g.ts': "import { f } from './f';\nexport const g = f;\n" });
    write(root, 'src/g.ts', "import { f, missing } from './f';\nexport const g = [f, missing];\n");
    const c = context((await runHook('after-tools', payload(root, 'src/g.ts'))).stdout)!;
    expect(c.additionalContext).toContain('missing');
  });

  it('carries the live session ledger\'s facts', async () => {
    const root = repo({ 'src/f.ts': 'export function f() { return 1; }\n' });
    const now = new Date().toISOString();
    write(root, `.openlore/session-ledger/${process.pid}.json`, JSON.stringify({
      schemaVersion: 1, pid: process.pid, root, startedAt: now, updatedAt: now, editSource: 'watcher', agentEditsReported: true,
      counts: { served: 1, edited: 1, untracked: 0, dropped: 0 },
      backgroundChanges: [{ id: 'src/f.ts::f', name: 'f', file: 'src/f.ts', servedAt: now, changedAt: now }], editOscillation: [],
    }));
    const c = context((await runHook('after-tools', payload(root))).stdout)!;
    expect(c.additionalContext).toContain('f (src/f.ts) changed since this session read it');
  });

  it('prints nothing when nothing is new, and nothing on a timeout', async () => {
    const root = repo({ 'src/f.ts': 'export function f() { return 1; }\n' });
    write(root, 'src/f.ts', 'export function f() { return 2; }\n');
    expect((await runHook('after-tools', payload(root, 'src/f.ts'))).stdout).toBe('');
    write(root, 'src/f.test.ts', TEST.replace("it('b'", "it.skip('b'"));
    expect(await runHook('after-tools', payload(root, 'src/f.test.ts'), { timeoutMs: 1 })).toEqual({ stdout: '', exitCode: 0 });
  });
});

describe('before-stop', () => {
  const finding = { code: 'test-disabled', subject: 'src/f.test.ts::b', message: '`it.skip` was added to test `b`. The test file reaches f.', remediation: 'Test src/f.test.ts::b no longer runs; re-enable it, or record why it is off.' };

  it('prints the receipt without blocking by default', async () => {
    const root = repo();
    verify.result = { items: [{ subject: finding.message, check: 'check_weakening', severity: 'error', nextAction: finding.remediation }], findings: [{ ...finding, enforcementClass: 'advisory' }], gated: false };
    const r = await runHook('before-stop', payload(root));
    const c = context(r.stdout)!;
    expect(c.hookEventName).toBe('Stop');
    expect(c.additionalContext).toContain('(next action: Test src/f.test.ts::b no longer runs');
    expect(r.stdout).not.toContain('"decision"');
  });

  it('blocks only when the policy makes a finding blocking, and never twice in a row', async () => {
    const root = repo();
    verify.result = { items: [], findings: [{ ...finding, enforcementClass: 'blocking' }], gated: true };
    const r = JSON.parse((await runHook('before-stop', payload(root))).stdout) as { decision: string; reason: string };
    expect(r.decision).toBe('block');
    expect(r.reason).toContain('test-disabled: `it.skip` was added to test `b`');
    expect((await runHook('before-stop', payload(root, undefined, { stop_hook_active: true }))).stdout).toBe('');
  });

  it('no log line reaches stdout while the receipt is computed', async () => {
    const root = repo();
    verify.result = { items: [], gated: false };
    const out = vi.spyOn(process.stdout, 'write');
    const log = vi.spyOn(console, 'log');
    await runHook('before-stop', payload(root));
    expect(out).not.toHaveBeenCalled();
    expect(log).not.toHaveBeenCalled();
    out.mockRestore();
    log.mockRestore();
  });

  it('an unavailable receipt prints nothing', async () => {
    const root = repo();
    verify.result = { error: 'no index' };
    expect((await runHook('before-stop', payload(root))).stdout).toBe('');
  });
});

describe('wording', () => {
  it('adds no imperative of its own', () => {
    const out = renderReceipt('after-tools', [{ key: 'k', severity: 'warning', text: 'A fact.', next: 'the check concerned' }])!;
    expect(out).toBe('[openlore after-tools]\n- A fact. (next action: the check concerned)');
  });
});

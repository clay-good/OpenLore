/**
 * The fail-open contract of every agent-loop hook moment (change: hook-reliability, task 2.1;
 * spec `LoopHooksAreAdvisoryUnlessPolicyBlocks`).
 *
 * A hook runs on every prompt and every edit, so a broken one would hurt every turn. For each moment
 * and each way it can break (a check that throws or does not load, a time limit, a missing, wrong,
 * corrupt, or read-only `.openlore/`, a corrupt session record, a missing or truncated index, and an
 * empty or unreadable payload), `runHook` must resolve to `{ stdout: '', exitCode: 0 }`.
 *
 * The throwing-check cases are not vacuous: each payload makes its moment print a receipt when the
 * checks work (asserted first, in the control case), so silence there proves the error was absorbed.
 */
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { chmodSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

type RunHook = typeof import('./hook.js').runHook;
type Moment = Parameters<RunHook>[0];

const SILENT = { stdout: '', exitCode: 0 };
const GIT_ENV = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null', GIT_AUTHOR_NAME: 'T', GIT_AUTHOR_EMAIL: 't@e', GIT_COMMITTER_NAME: 'T', GIT_COMMITTER_EMAIL: 't@e' };
const GENERATED = '// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: order.proto\npackage gen\n';
const TEST = "import { f } from './f';\nit('a', () => { expect(f()).toBe(1); });\nit('b', () => { expect(f()).toBe(2); });\n";

const dirs: string[] = [];
const readOnly: string[] = [];

function write(root: string, rel: string, content: string): void {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), content);
}

/** A git repository set up for OpenLore, whose payloads below make each moment print a receipt. */
function repo(): string {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'olfailopen-')));
  dirs.push(root);
  mkdirSync(join(root, '.openlore'));
  writeFileSync(join(root, '.openlore', 'config.json'), '{}');
  write(root, '.gitignore', '.openlore/\n');
  write(root, 'gen/order.pb.go', GENERATED);
  write(root, 'src/f.ts', 'export function f() { return 1; }\n');
  write(root, 'src/f.test.ts', TEST);
  execFileSync('git', ['init', '-q', '-b', 'main'], { cwd: root, env: GIT_ENV });
  execFileSync('git', ['add', '-A'], { cwd: root, env: GIT_ENV });
  execFileSync('git', ['commit', '-qm', 'init'], { cwd: root, env: GIT_ENV });
  // The session's change: a weakened test (after-tools states it).
  write(root, 'src/f.test.ts', TEST.replace("it('b'", "it.skip('b'"));
  return root;
}

/** One payload per moment, in Claude Code's shape. */
function payload(moment: Moment, root: string, editTarget = 'gen/order.pb.go'): string {
  const base = { session_id: 's1', cwd: root };
  switch (moment) {
    case 'before-edit': return JSON.stringify({ ...base, tool_name: 'Edit', tool_input: { file_path: join(root, editTarget), old_string: 'package gen', new_string: 'package gen2' } });
    case 'after-tools': return JSON.stringify({ ...base, tool_name: 'Edit', tool_input: { file_path: join(root, 'src/f.test.ts') }, tool_response: {} });
    case 'before-stop': return JSON.stringify({ ...base, stop_hook_active: false });
    case 'after-compact': return JSON.stringify({ ...base, source: 'compact' });
    case 'before-subagent': return JSON.stringify({ ...base, tool_name: 'Agent', tool_input: { prompt: 'rename f', subagent_type: 'general-purpose' } });
    case 'subagent-start': return JSON.stringify({ ...base, agent_type: 'general-purpose' });
  }
}
const SHELL = (root: string) => JSON.stringify({ session_id: 's1', cwd: root, tool_name: 'Bash', tool_input: { command: 'npm test' }, tool_response: { exit_code: 0 } });

/** Every module a moment loads to compute its receipt, with the exports it calls. */
const CHECK_MODULES: Record<string, string[]> = {
  '../../core/services/generated-file-guard.js': ['classifyGeneratedFiles', 'emittedText'],
  '../../core/services/phantom-references.js': ['checkPhantomReferences'],
  '../../core/services/check-weakening.js': ['checkWeakening'],
  '../../core/services/session-ledger.js': ['recordAgentEdit', 'readLiveLedger'],
  '../../core/services/test-run-ledger.js': ['recordEditIntent', 'recordEdits', 'recordShellCommand', 'editsAfterLastRun'],
  '../../core/services/peer-notices.js': ['peerChangeNotices'],
  '../../core/services/mcp-handlers/verify-change.js': ['handleVerifyChange'],
  '../../core/services/mcp-handlers/handoff.js': ['handleGetHandoffBriefing', 'renderHandoff'],
  '../../core/services/subagent-briefing.js': ['queueSubagentTask', 'takeSubagentTask', 'subagentBriefing'],
  '../../core/drift/git-diff.js': ['classifyFile', 'getRepoPrefix'],
  '../../utils/git-exec.js': ['execFileGit'],
};

/** The verify-change receipt the control case needs (the real one needs an index). */
function mockVerifyChangeWithAFinding(): void {
  vi.doMock('../../core/services/mcp-handlers/verify-change.js', () => ({
    handleVerifyChange: async () => ({ items: [{ subject: 'src/f.test.ts', check: 'test-disabled', severity: 'warning', nextAction: 're-enable the test' }] }),
  }));
}
function mockHandoffWithABriefing(): void {
  vi.doMock('../../core/services/mcp-handlers/handoff.js', () => ({
    handleGetHandoffBriefing: async () => ({}),
    renderHandoff: () => '[openlore handoff] one change in flight',
  }));
}
function mockSubagentBriefing(): void {
  vi.doMock('../../core/services/subagent-briefing.js', () => ({
    queueSubagentTask: async () => undefined,
    takeSubagentTask: async () => 'rename f',
    subagentBriefing: async () => '[openlore subagent] briefing',
  }));
}

async function loadRunHook(): Promise<RunHook> {
  return (await import('./hook.js')).runHook;
}

beforeEach(() => { vi.resetModules(); });
afterEach(() => {
  vi.doUnmock('../../core/services/mcp-handlers/verify-change.js');
  for (const m of Object.keys(CHECK_MODULES)) vi.doUnmock(m);
  for (const d of readOnly.splice(0)) { try { chmodSync(d, 0o755); } catch { /* gone */ } }
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
});

const MOMENTS: Moment[] = ['before-edit', 'after-tools', 'before-stop', 'after-compact', 'before-subagent', 'subagent-start'];
/** The moments that print a receipt for the payloads above when their checks work. */
const SPEAKING: Moment[] = ['before-edit', 'after-tools', 'before-stop', 'after-compact', 'subagent-start'];

describe('control: the payloads make each moment speak when its checks work', () => {
  it.each(SPEAKING)('%s prints a receipt', async (moment) => {
    mockVerifyChangeWithAFinding();
    mockHandoffWithABriefing();
    mockSubagentBriefing();
    const runHook = await loadRunHook();
    const r = await runHook(moment, payload(moment, repo()));
    expect(r.exitCode).toBe(0);
    expect(r.stdout).not.toBe('');
    expect(() => JSON.parse(r.stdout)).not.toThrow();
  });
});

describe('a check that throws is silent', () => {
  it.each(MOMENTS)('%s: every check function throws', async (moment) => {
    for (const [path, names] of Object.entries(CHECK_MODULES)) {
      vi.doMock(path, () => Object.fromEntries(names.map(n => [n, () => { throw new Error(`${n} broke`); }])));
    }
    const runHook = await loadRunHook();
    await expect(runHook(moment, payload(moment, repo()))).resolves.toEqual(SILENT);
  });

  it.each(MOMENTS)('%s: every check rejects (a sync check throws)', async (moment) => {
    for (const [path, names] of Object.entries(CHECK_MODULES)) {
      // Keep each function's kind: hook.ts calls some sync checks without awaiting them.
      const real = await vi.importActual<Record<string, unknown>>(path);
      vi.doMock(path, () => Object.fromEntries(names.map(n => [n, (real[n] as { constructor: { name: string } }).constructor.name === 'AsyncFunction'
        ? async () => { throw new Error(`${n} broke`); }
        : () => { throw new Error(`${n} broke`); }])));
    }
    const runHook = await loadRunHook();
    await expect(runHook(moment, payload(moment, repo()))).resolves.toEqual(SILENT);
  });

  it.each(MOMENTS)('%s: no check module loads', async (moment) => {
    for (const path of Object.keys(CHECK_MODULES)) {
      vi.doMock(path, () => { throw new Error(`cannot load ${path}`); });
    }
    const runHook = await loadRunHook();
    await expect(runHook(moment, payload(moment, repo()))).resolves.toEqual(SILENT);
  });

  it('after-tools for a shell command: the run ledger does not load', async () => {
    vi.doMock('../../core/services/test-run-ledger.js', () => { throw new Error('cannot load'); });
    const runHook = await loadRunHook();
    await expect(runHook('after-tools', SHELL(repo()))).resolves.toEqual(SILENT);
  });
});

describe('a time limit of 1 ms is silent', () => {
  it.each(SPEAKING)('%s', async (moment) => {
    mockVerifyChangeWithAFinding();
    // Slow checks: each answer arrives after the limit.
    vi.doMock('../../core/services/mcp-handlers/handoff.js', () => ({
      handleGetHandoffBriefing: () => new Promise(r => setTimeout(() => r({}), 200)),
      renderHandoff: () => '[openlore handoff] late',
    }));
    vi.doMock('../../core/services/subagent-briefing.js', () => ({
      queueSubagentTask: async () => undefined,
      takeSubagentTask: async () => 'rename f',
      subagentBriefing: () => new Promise(r => setTimeout(() => r('[openlore subagent] late'), 200)),
    }));
    const runHook = await loadRunHook();
    await expect(runHook(moment, payload(moment, repo()), { timeoutMs: 1 })).resolves.toEqual(SILENT);
  });
});

describe('a check that fails after the time limit', () => {
  it.each(SPEAKING)('%s: a rejection after the limit stays handled', async (moment) => {
    const late = () => new Promise((_, reject) => setTimeout(() => reject(new Error('late')), 30));
    vi.doMock('../../core/services/mcp-handlers/verify-change.js', () => ({ handleVerifyChange: late }));
    vi.doMock('../../core/services/mcp-handlers/handoff.js', () => ({ handleGetHandoffBriefing: late, renderHandoff: () => 'x' }));
    vi.doMock('../../core/services/subagent-briefing.js', () => ({ queueSubagentTask: late, takeSubagentTask: async () => 'p', subagentBriefing: late }));
    vi.doMock('../../core/services/generated-file-guard.js', () => ({ classifyGeneratedFiles: late, emittedText: (t: string) => t }));
    vi.doMock('../../core/services/session-ledger.js', () => ({ recordAgentEdit: () => undefined, readLiveLedger: () => ({}) }));
    const unhandled: unknown[] = [];
    const onUnhandled = (e: unknown) => { unhandled.push(e); };
    process.on('unhandledRejection', onUnhandled);
    try {
      const runHook = await loadRunHook();
      await expect(runHook(moment, payload(moment, repo()), { timeoutMs: 1 })).resolves.toEqual(SILENT);
      await new Promise(r => setTimeout(r, 80)); // the checks reject now
      expect(unhandled).toEqual([]);
    } finally {
      process.off('unhandledRejection', onUnhandled);
    }
  });
});

/** A broken store, set up by `breakStore(root)`. Each moment's real checks then run on it. */
const BROKEN_STORES: Array<[string, (root: string) => void]> = [
  ['no .openlore directory', root => rmSync(join(root, '.openlore'), { recursive: true, force: true })],
  ['.openlore is a file', root => { rmSync(join(root, '.openlore'), { recursive: true, force: true }); writeFileSync(join(root, '.openlore'), 'not a directory'); }],
  ['config.json is corrupt', root => writeFileSync(join(root, '.openlore', 'config.json'), '{"hooks": {')],
  ['config.json is the wrong shape', root => writeFileSync(join(root, '.openlore', 'config.json'), '[1, "hooks", null]')],
  ['the session record is corrupt', root => {
    const id = createHash('sha256').update('s1').digest('hex').slice(0, 24);
    write(root, `.openlore/session-ledger/hook-delivered/${id}.json`, '{"startHead": 42, "keys": {');
  }],
  ['the session record names a foreign start commit', root => {
    const id = createHash('sha256').update('s1').digest('hex').slice(0, 24);
    write(root, `.openlore/session-ledger/hook-delivered/${id}.json`, JSON.stringify({ startHead: 'f'.repeat(40), keys: [] }));
  }],
  ['the index files are truncated', root => {
    write(root, '.openlore/analysis/llm-context.json', '{"callGraph": {"nodes": [');
    write(root, '.openlore/analysis/call-graph.db', 'SQLite format 3\0truncated');
  }],
  ['.openlore is read-only', root => {
    if (process.platform === 'win32' || process.getuid?.() === 0) return; // chmod does not bind there
    chmodSync(join(root, '.openlore'), 0o555);
    readOnly.push(join(root, '.openlore'));
  }],
];

describe('a broken store: the real checks run and every moment is silent or a well-formed receipt', () => {
  for (const [name, breakStore] of BROKEN_STORES) {
    it.each(MOMENTS)(`${name}: %s exits 0 and says nothing about the breakage`, async (moment) => {
      const runHook = await loadRunHook();
      const root = repo();
      breakStore(root);
      const r = await runHook(moment, payload(moment, root));
      expect(r.exitCode).toBe(0);
      // Evidence that does not need the broken part (a generated target, a weakened test) may still
      // be stated; an error, a stack, or a pointer about the breakage may not.
      if (r.stdout) {
        const out = JSON.parse(r.stdout) as { hookSpecificOutput?: { additionalContext?: string }; systemMessage?: string };
        const text = out.hookSpecificOutput?.additionalContext ?? out.systemMessage ?? '';
        expect(text).toMatch(/^\[openlore /);
        expect(text).not.toMatch(/\b(error|exception|ENOENT|EACCES|EISDIR|ENOTDIR|SyntaxError|stack|corrupt|cannot|failed)\b/i);
      }
    });
  }

  /** The spec's four moments (after-compact always states the git state of the change). */
  const QUIET_ON_A_CLEAN_TREE: Moment[] = ['before-edit', 'after-tools', 'before-stop', 'before-subagent', 'subagent-start'];
  it.each(QUIET_ON_A_CLEAN_TREE)('a corrupt config.json and index together (the spec scenario): %s', async (moment) => {
    const runHook = await loadRunHook();
    const root = repo();
    writeFileSync(join(root, '.openlore', 'config.json'), '{"hooks": {');
    write(root, '.openlore/analysis/llm-context.json', '{');
    write(root, '.openlore/analysis/call-graph.db', 'not sqlite');
    // An ordinary file and no session change: nothing for any check to state.
    execFileSync('git', ['checkout', '--', 'src/f.test.ts'], { cwd: root, env: GIT_ENV });
    const ordinary = payload(moment, root, 'src/f.ts');
    await expect(runHook(moment, ordinary)).resolves.toEqual(SILENT);
  });

  it('after-compact on a broken store states the git state, not the breakage', async () => {
    const runHook = await loadRunHook();
    const root = repo();
    // The project is set up, but its store is broken: the analysis folder is a file.
    writeFileSync(join(root, '.openlore', 'analysis'), 'not a directory');
    const r = await runHook('after-compact', payload('after-compact', root));
    const text = (JSON.parse(r.stdout) as { hookSpecificOutput: { additionalContext: string } }).hookSpecificOutput.additionalContext;
    expect(text).toContain('Uncommitted: 0 staged, 1 unstaged');
    expect(text).toMatch(/part\(s\) of this briefing could not be computed; `openlore handoff` names them\./);
    expect(text).not.toContain(root);
    expect(text).not.toMatch(/ENOTDIR|lstat|escape/);
  });
});

describe('no usable index', () => {
  it('subagent-start gives a queued task no "run openlore analyze" pointer', async () => {
    const runHook = await loadRunHook();
    const root = repo();
    await runHook('before-subagent', payload('before-subagent', root));
    await expect(runHook('subagent-start', payload('subagent-start', root))).resolves.toEqual(SILENT);
  });
});

describe('an unreadable payload is silent', () => {
  const PAYLOADS: Array<[string, string]> = [
    ['empty stdin', ''],
    ['non-JSON stdin', 'this is not json {'],
    ['a JSON array', '[1,2,3]'],
    ['JSON null', 'null'],
    ['wrong field types', JSON.stringify({ session_id: 7, cwd: ['x'], tool_name: {}, tool_input: 'x', tool_response: 3, stop_hook_active: 'yes' })],
    ['a file outside the repository', JSON.stringify({ session_id: 's1', tool_name: 'Edit', tool_input: { file_path: '/etc/passwd' } })],
  ];
  for (const [name, raw] of PAYLOADS) {
    it.each(MOMENTS)(`${name}: %s`, async (moment) => {
      const runHook = await loadRunHook();
      const root = repo();
      // No cwd in the payload: the hook falls back to the process's (here, the repository).
      const r = await runHook(moment, raw, { cwd: root });
      expect(r.exitCode).toBe(0);
      // before-stop and after-compact may still answer for the repository itself; nothing may break.
      if (r.stdout) expect(() => JSON.parse(r.stdout)).not.toThrow();
      if (moment === 'before-edit' || moment === 'before-subagent') expect(r).toEqual(SILENT);
    });
  }
});

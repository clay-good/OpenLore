const ENV = {
  ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null',
  GIT_AUTHOR_NAME: 'T', GIT_AUTHOR_EMAIL: 't@e.com', GIT_COMMITTER_NAME: 'T', GIT_COMMITTER_EMAIL: 't@e.com',
};
const git = (cwd: string, args: string[]) => execFileSync('git', args, { cwd, stdio: 'ignore', env: ENV });
const write = (cwd: string, rel: string, content: string) => {
  const p = join(cwd, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, content);
};

let dirs: string[] = [];
afterEach(() => {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
  dirs = [];
});

/** A git repository with `files` committed, then `edits` written to the working tree. */
function repo(files: Record<string, string>, edits: Record<string, string> = {}): string {
  const d = mkdtempSync(join(tmpdir(), 'openlore-genguard-'));
  dirs.push(d);
  git(d, ['init', '-q', '-b', 'main']);
  for (const [f, c] of Object.entries(files)) write(d, f, c);
  git(d, ['add', '-A']);
  git(d, ['commit', '-q', '-m', 'base']);
  for (const [f, c] of Object.entries(edits)) write(d, f, c);
  return d;
}

// Header fixtures are assembled from parts so this test file's own header never reads as generated.
const GO_HEADER = ['// Code generated by protoc-gen-go.', 'DO NOT EDIT.'].join(' ');
const PB_GO = [GO_HEADER, '// source: order.proto', '', 'package gen', ''].join('\n');
const AT_GENERATED = ['// @gene', 'rated', '\nexport const x = 1;\n'].join('');

const fact = (over: Partial<GeneratedFileFact> & { file: string }): GeneratedFileFact => ({
  rule: 'header-marker', matched: 'go-code-generated', kind: 'generated',
  generatedFrom: 'unknown', regenerateWith: 'unknown', certainty: 'declared', ...over,
});

describe('header markers (closed list)', () => {
  it('recognizes the Go convention exactly', () => {
    expect(matchHeaderMarker(PB_GO)).toBe('go-code-generated');
    // The Go rule needs the exact line; a trailing word breaks it (the broader rule still applies).
    expect(matchHeaderMarker(GO_HEADER + ' Really.')).toBe('generated-do-not-edit');
  });

  it('recognizes @generated only as the first token of a comment', () => {
    expect(matchHeaderMarker(AT_GENERATED)).toBe('at-generated');
    expect(matchHeaderMarker(['/** @gene', 'rated */\n'].join(''))).toBe('at-generated');
    // Mentioned inside prose or a string literal: not a marker.
    expect(matchHeaderMarker(['// we strip the `@gene', 'rated` tag\n'].join(''))).toBeNull();
    expect(matchHeaderMarker(["const tag = '@gene", "rated';\n"].join(''))).toBeNull();
  });

  it('recognizes generated + do-not-edit banners and auto-generated tags in comments only', () => {
    expect(matchHeaderMarker(['# Generated by the protocol buffer compiler.', 'DO NOT EDIT!'].join('  '))).toBe('generated-do-not-edit');
    expect(matchHeaderMarker(['// <auto-', 'generated />'].join(''))).toBe('auto-generated-banner');
    expect(matchHeaderMarker(['/*', ' * This file was automatically gen', 'erated.', ' */'].join('\n').replace('gen\n', 'gen'))).toBe('auto-generated-banner');
    expect(matchHeaderMarker(['const s = "generated, do not ', 'edit";'].join(''))).toBeNull();
  });

  it('does not detect a header outside the closed list or past the scanned lines', () => {
    expect(matchHeaderMarker('// produced by our tool, please leave alone\n')).toBeNull();
    const late = Array.from({ length: 45 }, () => '// filler').join('\n') + '\n' + GO_HEADER + '\n';
    expect(matchHeaderMarker(late)).toBeNull();
  });

  it('reads literal header sources and drops sentence punctuation', () => {
    expect(headerSources(PB_GO)).toEqual(['order.proto']);
    expect(headerSources(['// This file was generated from openapi.yaml.', 'Do not edit.'].join(' '))).toEqual(['openapi.yaml']);
    expect(headerSources('// nothing here\n')).toEqual([]);
  });
});

describe('command parsing (literal only)', () => {
  it('splits simple commands and honors quotes', () => {
    expect(tokenizeCommand('a b && c "d e" ; f > out.txt')).toEqual([['a', 'b'], ['c', 'd e'], ['f', '>', 'out.txt']]);
  });

  it('reads protoc, -o / --output, and redirection outputs, and literal inputs', () => {
    expect(commandPaths(['protoc', '--go_out=paths=source_relative:gen', 'proto/order.proto']))
      .toEqual({ outputs: ['gen'], inputs: ['proto/order.proto'] });
    expect(commandPaths(['openapi-generator-cli', 'generate', '-i', 'openapi.yaml', '-o', 'src/gen']))
      .toEqual({ outputs: ['src/gen'], inputs: ['generate', 'openapi.yaml'] });
    expect(commandPaths(['tool', 'in.json', '>', 'gen/out.ts'])).toEqual({ outputs: ['gen/out.ts'], inputs: ['in.json'] });
  });

  it('drops globs, variables, and URLs instead of expanding them', () => {
    expect(commandPaths(['protoc', '--go_out=$OUT', 'proto/*.proto', 'https://x/y.yaml'])).toEqual({ outputs: [], inputs: [] });
  });
});

describe('classifyGeneratedFiles', () => {
  it('names the source and command from a go:generate directive (spec scenario)', async () => {
    const d = repo({
      'generate.go': 'package main\n\n//go:generate protoc --go_out=gen proto/order.proto\n',
      'proto/order.proto': 'syntax = "proto3";\n',
      'gen/order_pb.go': PB_GO,
    });
    const { facts } = await classifyGeneratedFiles(d, ['gen/order_pb.go']);
    const f = facts.get('gen/order_pb.go')!;
    expect(f).toMatchObject({
      rule: 'header-marker', matched: 'go-code-generated', kind: 'generated', certainty: 'declared',
      generatedFrom: ['proto/order.proto'],
      regenerateWith: 'protoc --go_out=gen proto/order.proto',
      configFile: 'generate.go',
    });
    expect(f.evidence).toContain('go:generate in generate.go:3');
  });

  it('records unknown, never a guess, when nothing names the source (spec scenario)', async () => {
    const d = repo({ 'src/client.ts': AT_GENERATED, 'schema.graphql': 'type Q { a: Int }\n' });
    const f = (await classifyGeneratedFiles(d, ['src/client.ts'])).facts.get('src/client.ts')!;
    expect(f).toMatchObject({ rule: 'header-marker', matched: 'at-generated', generatedFrom: 'unknown', regenerateWith: 'unknown' });
  });

  it('reports a header literal as written when it does not resolve', async () => {
    const d = repo({ 'gen/x.go': [GO_HEADER, '// source: elsewhere/x.proto', 'package gen', ''].join('\n') });
    const f = (await classifyGeneratedFiles(d, ['gen/x.go'])).facts.get('gen/x.go')!;
    expect(f.generatedFrom).toEqual(['elsewhere/x.proto']);
    expect(f.evidence?.[0]).toContain('not found');
  });

  it('never resolves a header literal outside the repository', async () => {
    const d = repo({ 'gen/x.go': [GO_HEADER, '// source: ../../../../etc/hosts', 'package gen', ''].join('\n') });
    const f = (await classifyGeneratedFiles(d, ['gen/x.go'])).facts.get('gen/x.go')!;
    expect(f.generatedFrom).toEqual(['../../../../etc/hosts']);
    expect(f.evidence?.[0]).toContain('not found');
  });

  it('detects linguist-generated and linguist-vendored through .gitattributes', async () => {
    const d = repo({
      '.gitattributes': 'api/*.ts linguist-generated\nthird_party/** linguist-vendored\n',
      'api/client.ts': 'export const a = 1;\n',
      'third_party/lib/x.js': 'module.exports = 1;\n',
      'src/plain.ts': 'export const b = 2;\n',
    });
    const { facts } = await classifyGeneratedFiles(d, ['api/client.ts', 'third_party/lib/x.js', 'src/plain.ts']);
    expect(facts.get('api/client.ts')).toMatchObject({ rule: 'gitattributes', matched: 'linguist-generated', kind: 'generated' });
    expect(facts.get('third_party/lib/x.js')).toMatchObject({ rule: 'gitattributes', matched: 'linguist-vendored', kind: 'vendored' });
    expect(facts.has('src/plain.ts')).toBe(false);
  });

  it('classifies lockfiles by name with the manifests present', async () => {
    const d = repo({ 'package.json': '{}\n', 'package-lock.json': '{}\n', 'go.sum': '' });
    const { facts } = await classifyGeneratedFiles(d, ['package-lock.json', 'go.sum']);
    expect(facts.get('package-lock.json')).toMatchObject({ rule: 'lockfile', kind: 'lockfile', generatedFrom: ['package.json'] });
    expect(facts.get('go.sum')).toMatchObject({ rule: 'lockfile', generatedFrom: 'unknown' });
  });

  it('falls back to path patterns with lower certainty, and honors an explicit opt-out', async () => {
    const d = repo({
      '.gitattributes': 'types/*.d.ts -linguist-generated\n',
      'vendor/dep/a.go': 'package dep\n',
      'src/x.generated.ts': 'export {};\n',
      'types/hand.d.ts': 'declare const x: number;\n',
    });
    const { facts } = await classifyGeneratedFiles(d, ['vendor/dep/a.go', 'src/x.generated.ts', 'types/hand.d.ts']);
    expect(facts.get('vendor/dep/a.go')).toMatchObject({ rule: 'path-pattern', kind: 'vendored', certainty: 'path-pattern' });
    expect(facts.get('src/x.generated.ts')).toMatchObject({ rule: 'path-pattern', matched: '*.generated.*', certainty: 'path-pattern' });
    expect(facts.has('types/hand.d.ts')).toBe(false);
  });

  it('a header marker outranks the path pattern', async () => {
    const d = repo({ 'generated/a.go': PB_GO });
    expect((await classifyGeneratedFiles(d, ['generated/a.go'])).facts.get('generated/a.go')?.rule).toBe('header-marker');
  });

  it('names source and command from a package.json script', async () => {
    const d = repo({
      'package.json': JSON.stringify({ scripts: { gen: 'openapi-generator-cli generate -i openapi.yaml -o src/gen' } }),
      'openapi.yaml': 'openapi: 3.0.0\n',
      'src/gen/api.ts': ['// This file was generated by openapi-generator.', 'Do not edit.'].join(' ') + '\n',
    });
    const f = (await classifyGeneratedFiles(d, ['src/gen/api.ts'])).facts.get('src/gen/api.ts')!;
    expect(f).toMatchObject({ generatedFrom: ['openapi.yaml'], regenerateWith: 'openapi-generator-cli generate -i openapi.yaml -o src/gen', configFile: 'package.json' });
    expect(f.evidence).toContain('package.json script "gen" in package.json');
  });

  it('names source and command from a Makefile recipe in an ancestor directory', async () => {
    const d = repo({
      'svc/Makefile': '.PHONY: gen\ngen:\n\t@protoc --python_out=out api.proto\n',
      'svc/api.proto': 'syntax = "proto3";\n',
      'svc/out/api_pb2.py': ['# Generated by the protocol buffer compiler.', 'DO NOT EDIT!'].join('  ') + '\n',
    });
    const f = (await classifyGeneratedFiles(d, ['svc/out/api_pb2.py'])).facts.get('svc/out/api_pb2.py')!;
    expect(f).toMatchObject({ generatedFrom: ['svc/api.proto'], regenerateWith: 'protoc --python_out=out api.proto', configFile: 'svc/Makefile' });
  });

  it('names source and command from a CI run step with a working directory', async () => {
    const d = repo({
      '.github/workflows/gen.yml': [
        'on: push', 'jobs:', '  gen:', '    runs-on: ubuntu-latest', '    steps:',
        '      - run: buf generate --template t.yaml -o gen schema.proto', '        working-directory: api', '',
      ].join('\n'),
      'api/schema.proto': 'syntax = "proto3";\n',
      'api/t.yaml': 'version: v1\n',
      'api/gen/schema_pb.ts': AT_GENERATED,
    });
    const f = (await classifyGeneratedFiles(d, ['api/gen/schema_pb.ts'])).facts.get('api/gen/schema_pb.ts')!;
    expect(f.regenerateWith).toBe('buf generate --template t.yaml -o gen schema.proto');
    // Every literal file the command reads is named: an unknown flag's value (the template) cannot
    // be told apart from an input without guessing at the tool's flags.
    expect(f.generatedFrom).toEqual(['api/t.yaml', 'api/schema.proto']);
    expect(f.configFile).toBe('.github/workflows/gen.yml');
  });

  it('ignores an entry whose output does not hold the file', async () => {
    const d = repo({
      'package.json': JSON.stringify({ scripts: { gen: 'tool -i a.json -o other' } }),
      'a.json': '{}', 'src/x.ts': AT_GENERATED,
    });
    expect((await classifyGeneratedFiles(d, ['src/x.ts'])).facts.get('src/x.ts')?.regenerateWith).toBe('unknown');
  });

  it('discloses when .gitattributes could not be read (not a git work tree)', async () => {
    const d = mkdtempSync(join(tmpdir(), 'openlore-genguard-nogit-'));
    dirs.push(d);
    write(d, 'a.go', PB_GO);
    const r = await classifyGeneratedFiles(d, ['a.go', '../escape.go']);
    expect(r.facts.get('a.go')?.rule).toBe('header-marker');
    expect(r.facts.size).toBe(1);
    expect(r.boundaries.join(' ')).toContain('.gitattributes');
  });
});

describe('generatedFileEditedFindings', () => {
  const pb = fact({ file: 'gen/order_pb.ts', generatedFrom: ['proto/order.proto'], regenerateWith: 'buf generate', configFile: 'buf.gen.yaml' });
  const facts = new Map([[pb.file, pb]]);

  it('is a registered, advisory finding code', () => {
    expect(isKnownFindingCode('generated-file-edited')).toBe(true);
    expect(sourceDefaultClass('generated-file-edited')).toBe('advisory');
  });

  it('fires when the generated file is edited alone, naming the source and command', () => {
    const [f, ...rest] = generatedFileEditedFindings([{ path: 'gen/order_pb.ts', status: 'modified' }], facts);
    expect(rest).toEqual([]);
    expect(f).toMatchObject({ code: 'generated-file-edited', severity: 'warning', subject: 'gen/order_pb.ts', location: { path: 'gen/order_pb.ts' } });
    expect(f.message).toContain('proto/order.proto');
    expect(f.message).toContain('`buf generate`');
  });

  it('does not fire when the source or the regenerating config changed too', () => {
    expect(generatedFileEditedFindings([
      { path: 'gen/order_pb.ts', status: 'modified' }, { path: 'proto/order.proto', status: 'modified' },
    ], facts)).toEqual([]);
    expect(generatedFileEditedFindings([
      { path: 'gen/order_pb.ts', status: 'modified' }, { path: 'buf.gen.yaml', status: 'modified' },
    ], facts)).toEqual([]);
  });

  it('does not fire for an added or deleted generated file', () => {
    expect(generatedFileEditedFindings([{ path: 'gen/order_pb.ts', status: 'added' }], facts)).toEqual([]);
    expect(generatedFileEditedFindings([{ path: 'gen/order_pb.ts', status: 'deleted' }], facts)).toEqual([]);
  });

  it('fires with the source stated unknown, and at info for a path-pattern-only match', () => {
    const unknown = fact({ file: 'a.ts' });
    const pattern = fact({ file: 'vendor/b.go', rule: 'path-pattern', matched: 'vendor/', kind: 'vendored', certainty: 'path-pattern' });
    const out = generatedFileEditedFindings(
      [{ path: 'a.ts', status: 'modified' }, { path: 'vendor/b.go', status: 'modified' }],
      new Map([[unknown.file, unknown], [pattern.file, pattern]]),
    );
    expect(out.map(f => [f.subject, f.severity])).toEqual([['a.ts', 'warning'], ['vendor/b.go', 'info']]);
    expect(out[0].message).toContain('its source is unknown');
    expect(out[1].message).toContain('path pattern only');
  });

  it('matches an unresolved header literal against a changed path by suffix', () => {
    const lit = fact({ file: 'gen/x.go', generatedFrom: ['x.proto'] });
    expect(generatedFileEditedFindings(
      [{ path: 'gen/x.go', status: 'modified' }, { path: 'proto/x.proto', status: 'modified' }],
      new Map([[lit.file, lit]]),
    )).toEqual([]);
  });

  it('fires for a lockfile changed without a manifest at or below its directory', () => {
    const lock = fact({ file: 'package-lock.json', rule: 'lockfile', matched: 'package-lock.json', kind: 'lockfile', generatedFrom: ['package.json'] });
    const m = new Map([[lock.file, lock]]);
    const alone = generatedFileEditedFindings([{ path: 'package-lock.json', status: 'modified' }], m);
    expect(alone).toHaveLength(1);
    expect(alone[0].severity).toBe('info');
    expect(generatedFileEditedFindings([
      { path: 'package-lock.json', status: 'modified' }, { path: 'packages/a/package.json', status: 'modified' },
    ], m)).toEqual([]);

    const nested = fact({ file: 'svc/Cargo.lock', rule: 'lockfile', matched: 'Cargo.lock', kind: 'lockfile' });
    expect(generatedFileEditedFindings([
      { path: 'svc/Cargo.lock', status: 'modified' }, { path: 'other/Cargo.toml', status: 'modified' },
    ], new Map([[nested.file, nested]]))).toHaveLength(1);
  });
});

describe('guardDiff over a real diff', () => {
  const base = {
    'generate.go': 'package main\n\n//go:generate protoc --go_out=gen proto/order.proto\n',
    'proto/order.proto': 'syntax = "proto3";\n',
    'gen/order_pb.go': PB_GO,
    'package.json': '{"name":"x"}\n',
    'package-lock.json': '{}\n',
  };

  it('editing gen/order_pb.go alone fires; the lockfile alone fires', async () => {
    const d = repo(base, { 'gen/order_pb.go': PB_GO + '// hand edit\n', 'package-lock.json': '{"x":1}\n' });
    const r = await guardDiff(d, 'HEAD');
    expect(r.findings.map(f => f.subject).sort()).toEqual(['gen/order_pb.go', 'package-lock.json']);
    // blast_radius marks with these facts: the lockfile is among them (spec: a changed lockfile is marked).
    expect(r.facts.find(f => f.file === 'package-lock.json')).toMatchObject({ rule: 'lockfile', generatedFrom: ['package.json'] });
    const go = r.findings.find(f => f.subject === 'gen/order_pb.go')!;
    expect(go.message).toContain('proto/order.proto');
    expect(go.message).toContain('protoc --go_out=gen proto/order.proto');
  });

  it('editing gen/order_pb.go with its proto does not fire', async () => {
    const d = repo(base, { 'gen/order_pb.go': PB_GO + '// regen\n', 'proto/order.proto': 'syntax = "proto3";\n// v2\n' });
    expect((await guardDiff(d, 'HEAD')).findings).toEqual([]);
  });

  it('frames paths on an analyzed subdirectory of the repository', async () => {
    const d = repo({ 'svc/gen/a.go': PB_GO }, { 'svc/gen/a.go': PB_GO + '// edit\n' });
    const r = await guardDiff(join(d, 'svc'), 'HEAD');
    expect(r.findings.map(f => f.subject)).toEqual(['gen/a.go']);
  });
});


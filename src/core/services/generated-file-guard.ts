function normalizeRel(file: string): string | null {
  const p = posix.normalize(file.replace(/\\/g, '/')).replace(/^\.\/+/, '').replace(/^\/+/, '');
  if (p === '' || p === '.' || p === '..' || p.startsWith('../')) return null;
  return p;
}

/** Read at most `maxBytes` from the start of a confined regular file; null when unreadable. */
async function readHead(root: string, rel: string, maxBytes: number): Promise<string | null> {
  let abs: string;
  try { abs = safeJoin(root, rel); } catch { return null; }
  let handle;
  try {
    handle = await open(abs, constants.O_RDONLY | constants.O_NONBLOCK);
  } catch { return null; }
  try {
    const st = await handle.stat();
    if (!st.isFile()) return null;
    const buf = Buffer.alloc(Math.min(maxBytes, st.size));
    const { bytesRead } = await handle.read(buf, 0, buf.length, 0);
    const head = buf.subarray(0, bytesRead);
    // A NUL byte in the head means binary content: no header markers to read.
    if (head.includes(0)) return null;
    return head.toString('utf-8');
  } catch {
    return null;
  } finally {
    await handle.close().catch(() => undefined);
  }
}

function headerLines(head: string): string[] {
  return head.split('\n').slice(0, HEADER_SCAN_LINES).map(l => l.replace(/\r$/, ''));
}

/** The first header marker that matches, by the closed list's order. */
export function matchHeaderMarker(head: string): string | null {
  const lines = headerLines(head);
  for (const marker of GENERATED_HEADER_MARKERS) {
    if (lines.some(l => marker.test(l))) return marker.id;
  }
  return null;
}

/** Source paths a header names literally. Trailing sentence punctuation is dropped. */
export function headerSources(head: string): string[] {
  const out: string[] = [];
  for (const line of headerLines(head)) {
    for (const re of HEADER_SOURCE_PATTERNS) {
      const m = re.exec(line);
      const lit = m?.[1]?.replace(/[.,;:)\]]+$/, '');
      if (lit && !out.includes(lit)) out.push(lit);
    }
  }
  return out;
}

type AttrState = 'set' | 'false' | 'unspecified';
interface GitAttrs { generated: AttrState; vendored: AttrState }

/** `git check-attr` for the linguist attributes; null when git cannot answer. */
async function readGitAttributes(root: string, files: string[]): Promise<Map<string, GitAttrs> | null> {
  const out = new Map<string, GitAttrs>();
  if (files.length === 0) return out;
  try {
    const { stdout } = await execFileGit(
      'git', ['check-attr', '-z', 'linguist-generated', 'linguist-vendored', '--', ...files],
      { cwd: root, maxBuffer: 16 * 1024 * 1024 },
    );
    const parts = stdout.split('\0');
    for (let i = 0; i + 2 < parts.length; i += 3) {
      const [path, attr, value] = [parts[i], parts[i + 1], parts[i + 2]];
      const state: AttrState = value === 'set' || value === 'true' ? 'set'
        : value === 'unset' || value === 'false' ? 'false' : 'unspecified';
      const entry = out.get(path) ?? { generated: 'unspecified', vendored: 'unspecified' };
      if (attr === 'linguist-generated') entry.generated = state;
      else if (attr === 'linguist-vendored') entry.vendored = state;
      out.set(path, entry);
    }
    return out;
  } catch {
    return null;
  }
}

function pathPatternKind(rel: string): { kind: 'generated' | 'vendored'; matched: string } | null {
  if (!isExcludedPath(rel)) return null;
  const p = '/' + rel;
  for (const seg of ['/node_modules/', '/vendor/', '/vendored/']) {
    if (p.includes(seg)) return { kind: 'vendored', matched: seg.slice(1) };
  }
  if (p.endsWith('.d.ts')) return { kind: 'generated', matched: '*.d.ts' };
  if (p.includes('.generated.')) return { kind: 'generated', matched: '*.generated.*' };
  if (p.includes('/__generated__/')) return { kind: 'generated', matched: '__generated__/' };
  return { kind: 'generated', matched: 'generated/' };
}

/**
 * Classify files (paths relative to `root`) by the closed, ordered rule set and resolve each
 * generated file's source and regenerate command. Files that match no rule are absent from the
 * result. Best-effort per file: an unreadable file simply skips the header rule.
 */
export async function classifyGeneratedFiles(rootDir: string, files: readonly string[]): Promise<ClassifyResult> {
  // Confined reads need an absolute root; a relative one would fail every read quietly.
  const root = resolve(rootDir);
  const facts = new Map<string, GeneratedFileFact>();
  const boundaries: string[] = [];
  const rels = [...new Set(files.map(normalizeRel).filter((p): p is string => p !== null))].sort();
  if (rels.length === 0) return { facts, boundaries };

  const attrs = await readGitAttributes(root, rels);
  if (attrs === null) {
    boundaries.push('`.gitattributes` could not be read (not a git work tree, or git failed); the linguist-generated / linguist-vendored rule did not run.');
  }
  const resolver = new SourceResolver(root);

  for (const rel of rels) {
    const head = await readHead(root, rel, HEADER_SCAN_BYTES);
    const marker = head === null ? null : matchHeaderMarker(head);
    const attr = attrs?.get(rel);
    const name = posix.basename(rel);
    let base: Omit<GeneratedFileFact, 'generatedFrom' | 'regenerateWith'> | null = null;

    if (marker) {
      base = { file: rel, rule: 'header-marker', matched: marker, kind: 'generated', certainty: 'declared' };
    } else if (attr?.generated === 'set') {
      base = { file: rel, rule: 'gitattributes', matched: 'linguist-generated', kind: 'generated', certainty: 'declared' };
    } else if (attr?.vendored === 'set') {
      base = { file: rel, rule: 'gitattributes', matched: 'linguist-vendored', kind: 'vendored', certainty: 'declared' };
    } else if (Object.prototype.hasOwnProperty.call(LOCKFILE_MANIFESTS, name)) {
      base = { file: rel, rule: 'lockfile', matched: name, kind: 'lockfile', certainty: 'declared' };
    } else if (attr?.generated !== 'false' && attr?.vendored !== 'false') {
      // An explicit `linguist-generated=false` (or `-linguist-generated`) opts a path out of the
      // weakest rule — the escape hatch for a hand-written `.d.ts` or an in-house `vendor/` tree.
      const pk = pathPatternKind(rel);
      if (pk) base = { file: rel, rule: 'path-pattern', matched: pk.matched, kind: pk.kind, certainty: 'path-pattern' };
    }
    if (!base) continue;

    if (base.kind === 'lockfile') {
      const dir = posix.dirname(rel);
      const present: string[] = [];
      for (const m of LOCKFILE_MANIFESTS[name]) {
        const candidate = dir === '.' ? m : `${dir}/${m}`;
        if (await resolver.isFile(candidate)) present.push(candidate);
      }
      facts.set(rel, {
        ...base,
        generatedFrom: present.length ? present : 'unknown',
        regenerateWith: 'unknown',
        ...(present.length ? { evidence: ['lockfile manifest table'] } : {}),
      });
      continue;
    }
    if (base.kind === 'vendored') {
      facts.set(rel, { ...base, generatedFrom: 'unknown', regenerateWith: 'unknown' });
      continue;
    }

    const resolved = await resolver.resolve(rel, head);
    facts.set(rel, { ...base, ...resolved });
  }
  return { facts, boundaries };
}


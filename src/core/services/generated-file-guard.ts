/** Longest repository-derived string a fact carries into agent context. */
export const MAX_EMITTED_TEXT = 512;
export const WITHHELD_TEXT = '[withheld: reads like an instruction]';

/**
 * Repository text bound for agent context (a command, a header literal, a script name): bounded,
 * credential-redacted, control characters removed, and withheld when it reads like an instruction.
 */
export function emittedText(text: string): string {
  const redacted = redactSecretText(text.slice(0, MAX_EMITTED_TEXT * 4)).value;
  // eslint-disable-next-line no-control-regex -- control characters are exactly what is removed
  let clean = redacted.replace(/[\u0000-\u001f\u007f-\u009f]+/g, ' ');
  if (clean.length > MAX_EMITTED_TEXT) clean = clean.slice(0, MAX_EMITTED_TEXT).replace(/[\uD800-\uDBFF]$/, '') + '…';
  return detectInjectionShapes(clean).length ? WITHHELD_TEXT : clean;
}

/** {@link emittedText} over every repository-derived field of a fact. */
function emittedFact(f: GeneratedFileFact): GeneratedFileFact {
  return {
    ...f,
    generatedFrom: f.generatedFrom === 'unknown' ? 'unknown' : f.generatedFrom.map(emittedText),
    regenerateWith: f.regenerateWith === 'unknown' ? 'unknown' : emittedText(f.regenerateWith),
    ...(f.evidence ? { evidence: f.evidence.map(emittedText) } : {}),
    ...(f.configFile ? { configFile: emittedText(f.configFile) } : {}),
  };
}

function normalizeRel(file: string): string | null {
  const p = posix.normalize(file.replace(/\\/g, '/')).replace(/^\.\/+/, '').replace(/^\/+/, '');
  if (p === '' || p === '.' || p === '..' || p.startsWith('../')) return null;
  return p;
}

/**
 * Open a confined path read-only: the canonical (symlink-resolved) target must sit inside the
 * root, and it is opened with O_NOFOLLOW so a symlink swapped in after the check is refused, and
 * O_NONBLOCK so a FIFO never blocks. Null when it cannot be opened that way.
 */
async function openConfined(root: string, rel: string): Promise<FileHandle | null> {
  try {
    const canonical = await realpath(safeJoin(root, rel));
    safeJoin(await realpath(root), canonical);
    return await open(canonical, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  } catch {
    return null;
  }
}

/** Read at most `maxBytes` from the start of a confined regular file; null when unreadable. */
async function readHead(root: string, rel: string, maxBytes: number): Promise<string | null> {
  const handle = await openConfined(root, rel);
  if (!handle) return null;
  try {
    const st = await handle.stat();
    if (!st.isFile()) return null;
    const buf = Buffer.alloc(Math.min(maxBytes, st.size));
    const { bytesRead } = await handle.read(buf, 0, buf.length, 0);
    const head = buf.subarray(0, bytesRead);
    // A NUL byte in the head means binary content: no header markers to read.
    if (head.includes(0)) return null;
    return head.toString('utf-8');
  } catch {
    return null;
  } finally {
    await handle.close().catch(() => undefined);
  }
}

/**
 * The file's leading comment block: lines up to the first one that is neither blank nor a comment
 * (the Go rule: the marker comes before the first non-comment text), within the scan limits. A
 * marker inside a string literal or after the code begins is therefore never read.
 */
function headerLines(head: string, file?: string): string[] {
  const lead = leadFor(file);
  const out: string[] = [];
  let inBlock: '*/' | '-->' | null = null;
  for (const raw of head.split('\n').slice(0, HEADER_SCAN_LINES)) {
    const line = raw.replace(/\r$/, '');
    if (inBlock) {
      // Inside a block comment every line is comment text; give it a comment token so the markers,
      // which read comment lines only, see it.
      out.push(lead.test(line) ? line : `${inBlock === '-->' ? '<!--' : '*'} ${line.trimStart()}`);
      if (line.includes(inBlock)) inBlock = null;
      continue;
    }
    if (line.trim() === '') continue;
    if (!lead.test(line)) break;
    out.push(line);
    const t = line.trimStart();
    if (t.startsWith('/*') && !t.slice(2).includes('*/')) inBlock = '*/';
    else if (t.startsWith('<!--') && !t.slice(4).includes('-->')) inBlock = '-->';
  }
  return out;
}

/**
 * The first header marker that matches, by the closed list's order. `file` (optional) selects the
 * comment syntax: in a Markdown or text file only an HTML comment counts, never a `#` heading.
 */
export function matchHeaderMarker(head: string, file?: string): string | null {
  const lines = headerLines(head, file);
  const lead = leadFor(file);
  for (const marker of GENERATED_HEADER_MARKERS) {
    if (lines.some(l => marker.test(l, lead))) return marker.id;
  }
  return null;
}

/** Source paths a header names literally. Trailing sentence punctuation is dropped. */
export function headerSources(head: string, file?: string): string[] {
  const out: string[] = [];
  for (const line of headerLines(head, file)) {
    for (const re of HEADER_SOURCE_PATTERNS) {
      const m = re.exec(line);
      const lit = m?.[1]?.replace(/[.,;:)\]]+$/, '');
      if (lit && looksLikePath(lit) && !out.includes(lit)) out.push(lit);
    }
  }
  return out;
}

type AttrState = 'set' | 'false' | 'unspecified';
interface GitAttrs { generated: AttrState; vendored: AttrState }

/** Paths per `git check-attr` call, so a large file list never exceeds the argv limit. */
const CHECK_ATTR_BATCH = 500;

/** `git check-attr` for the linguist attributes; null when git cannot answer. */
async function readGitAttributes(root: string, files: string[]): Promise<Map<string, GitAttrs> | null> {
  const out = new Map<string, GitAttrs>();
  if (files.length === 0) return out;
  try {
    let stdout = '';
    for (let i = 0; i < files.length; i += CHECK_ATTR_BATCH) {
      stdout += (await execFileGit(
        'git', ['check-attr', '-z', 'linguist-generated', 'linguist-vendored', '--', ...files.slice(i, i + CHECK_ATTR_BATCH)],
        { cwd: root, maxBuffer: 16 * 1024 * 1024 },
      )).stdout;
    }
    const parts = stdout.split('\0');
    for (let i = 0; i + 2 < parts.length; i += 3) {
      const [path, attr, value] = [parts[i], parts[i + 1], parts[i + 2]];
      const state: AttrState = value === 'set' || value === 'true' ? 'set'
        : value === 'unset' || value === 'false' ? 'false' : 'unspecified';
      const entry = out.get(path) ?? { generated: 'unspecified', vendored: 'unspecified' };
      if (attr === 'linguist-generated') entry.generated = state;
      else if (attr === 'linguist-vendored') entry.vendored = state;
      out.set(path, entry);
    }
    return out;
  } catch {
    return null;
  }
}

function pathPatternKind(rel: string): { kind: 'generated' | 'vendored'; matched: string } | null {
  if (!isExcludedPath(rel)) return null;
  const p = '/' + rel;
  for (const seg of ['/node_modules/', '/vendor/', '/vendored/']) {
    if (p.includes(seg)) return { kind: 'vendored', matched: seg.slice(1) };
  }
  if (p.endsWith('.d.ts')) return { kind: 'generated', matched: '*.d.ts' };
  if (p.includes('.generated.')) return { kind: 'generated', matched: '*.generated.*' };
  if (p.includes('/__generated__/')) return { kind: 'generated', matched: '__generated__/' };
  return { kind: 'generated', matched: 'generated/' };
}

/**
 * Classify files (paths relative to `root`) by the closed, ordered rule set and resolve each
 * generated file's source and regenerate command. Files that match no rule are absent from the
 * result. Best-effort per file: an unreadable file simply skips the header rule.
 */
export async function classifyGeneratedFiles(
  rootDir: string,
  files: readonly string[],
  opts: { raw?: boolean } = {},
): Promise<ClassifyResult> {
  // Confined reads need an absolute root; a relative one would fail every read quietly.
  const root = resolve(rootDir);
  const facts = new Map<string, GeneratedFileFact>();
  const boundaries: string[] = [];
  const rels = [...new Set(files.map(normalizeRel).filter((p): p is string => p !== null))].sort();
  if (rels.length === 0) return { facts, boundaries };

  const attrs = await readGitAttributes(root, rels);
  if (attrs === null) {
    boundaries.push('`.gitattributes` could not be read (not a git work tree, or git failed); the linguist-generated / linguist-vendored rule did not run.');
  }
  const resolver = new SourceResolver(root);

  for (const rel of rels) {
    const name = posix.basename(rel);
    const isLockfile = Object.prototype.hasOwnProperty.call(LOCKFILE_MANIFESTS, name);
    // A lockfile's own header (yarn's "AUTOGENERATED FILE. DO NOT EDIT") must not hide that its
    // source is its manifest, so a lockfile name is decided before the header is read.
    const head = isLockfile ? null : await readHead(root, rel, HEADER_SCAN_BYTES);
    const marker = head === null ? null : matchHeaderMarker(head, rel);
    const attr = attrs?.get(rel);
    let base: Omit<GeneratedFileFact, 'generatedFrom' | 'regenerateWith'> | null = null;

    if (isLockfile) {
      base = { file: rel, rule: 'lockfile', matched: name, kind: 'lockfile', certainty: 'declared' };
    } else if (marker) {
      base = { file: rel, rule: 'header-marker', matched: marker, kind: 'generated', certainty: 'declared' };
    } else if (attr?.generated === 'set') {
      base = { file: rel, rule: 'gitattributes', matched: 'linguist-generated', kind: 'generated', certainty: 'declared' };
    } else if (attr?.vendored === 'set') {
      base = { file: rel, rule: 'gitattributes', matched: 'linguist-vendored', kind: 'vendored', certainty: 'declared' };
    } else if (attr?.generated !== 'false' && attr?.vendored !== 'false') {
      // An explicit `linguist-generated=false` (or `-linguist-generated`) opts a path out of the
      // weakest rule — the escape hatch for a hand-written `.d.ts` or an in-house `vendor/` tree.
      const pk = pathPatternKind(rel);
      if (pk) base = { file: rel, rule: 'path-pattern', matched: pk.matched, kind: pk.kind, certainty: 'path-pattern' };
    }
    if (!base) continue;

    if (base.kind === 'lockfile') {
      const dir = posix.dirname(rel);
      const present: string[] = [];
      for (const m of LOCKFILE_MANIFESTS[name]) {
        const candidate = dir === '.' ? m : `${dir}/${m}`;
        if (await resolver.isFile(candidate)) present.push(candidate);
      }
      facts.set(rel, {
        ...base,
        generatedFrom: present.length ? present : 'unknown',
        regenerateWith: 'unknown',
        ...(present.length ? { evidence: ['lockfile manifest table'] } : {}),
      });
      continue;
    }
    if (base.kind === 'vendored') {
      facts.set(rel, { ...base, generatedFrom: 'unknown', regenerateWith: 'unknown' });
      continue;
    }

    const resolved = await resolver.resolve(rel, head);
    facts.set(rel, { ...base, ...resolved });
  }
  if (resolver.capped) {
    boundaries.push('A config source held more commands than the guard reads; commands past the limit were not matched, so a source or command may read `unknown`.');
  }
  // Every repository-derived string is bounded, redacted, and screened before it can reach an agent.
  // `raw` is for internal matching only (guardDiff), never for output.
  if (!opts.raw) for (const [k, f] of facts) facts.set(k, emittedFact(f));
  return { facts, boundaries };
}


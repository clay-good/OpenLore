/** How far into a file the header markers are looked for. */
export const HEADER_SCAN_LINES = 40;
export const HEADER_SCAN_BYTES = 8 * 1024;

/** A line that opens with a comment token, in any of the languages the guard reads. */
const COMMENT_LEAD = String.raw`^\s*(?:\/\/+!?|#+!?|\/\*+!?|\*+|--+|;+|<!--|%+)\s*`;

/**
 * The closed list of generator header markers. A header that matches none of these is NOT
 * detected; the list is published so a team can see what is and is not recognized.
 */
export const GENERATED_HEADER_MARKERS: ReadonlyArray<{ id: string; description: string; test: (line: string) => boolean }> = [
  {
    id: 'go-code-generated',
    description: 'The Go convention (https://go.dev/s/generatedcode): a line matching `^// Code generated .* DO NOT EDIT\\.$`.',
    test: line => /^\/\/ Code generated .* DO NOT EDIT\.$/.test(line),
  },
  {
    id: 'at-generated',
    description: 'A comment whose first token is `@generated` (Meta / Buck / Relay / protobuf-es convention).',
    test: line => new RegExp(COMMENT_LEAD + String.raw`@generated(?:\s|\*\/|$)`).test(line),
  },
  {
    id: 'generated-do-not-edit',
    description: 'One comment line that says the file is generated and says DO NOT EDIT (or DO NOT MODIFY), in any case.',
    test: line =>
      new RegExp(COMMENT_LEAD).test(line) &&
      /\b(?:auto-?)?generated\b/i.test(line) &&
      /\bdo not (?:edit|modify)\b/i.test(line),
  },
  {
    id: 'auto-generated-banner',
    description: 'A comment line with `<auto-generated>` (the .NET tag), `AUTO-GENERATED FILE`, or `This file is/was (automatically) generated`.',
    test: line =>
      new RegExp(COMMENT_LEAD).test(line) &&
      /<auto-generated\b|\bauto-?generated file\b|\bthis file (?:is|was|has been) (?:automatically |auto-?)?generated\b/i.test(line),
  },
];

/** The lockfile names the guard recognizes, each with the manifest(s) it is generated from. */
export const LOCKFILE_MANIFESTS: Readonly<Record<string, readonly string[]>> = {
  'package-lock.json': ['package.json'],
  'npm-shrinkwrap.json': ['package.json'],
  'yarn.lock': ['package.json'],
  'pnpm-lock.yaml': ['package.json', 'pnpm-workspace.yaml'],
  'bun.lock': ['package.json'],
  'bun.lockb': ['package.json'],
  'deno.lock': ['deno.json', 'deno.jsonc'],
  'Cargo.lock': ['Cargo.toml'],
  'go.sum': ['go.mod'],
  'Gemfile.lock': ['Gemfile'],
  'poetry.lock': ['pyproject.toml'],
  'uv.lock': ['pyproject.toml'],
  'pdm.lock': ['pyproject.toml'],
  'Pipfile.lock': ['Pipfile'],
  'composer.lock': ['composer.json'],
  'mix.lock': ['mix.exs'],
  'pubspec.lock': ['pubspec.yaml'],
  'Podfile.lock': ['Podfile'],
  'Package.resolved': ['Package.swift'],
  'flake.lock': ['flake.nix'],
  'gradle.lockfile': ['build.gradle', 'build.gradle.kts'],
};

/** Header lines that name the file's source literally (`source: order.proto`, `Generated from openapi.yaml`). */
const HEADER_SOURCE_PATTERNS: readonly RegExp[] = [
  new RegExp(COMMENT_LEAD + String.raw`source:\s*([^\s"'\x60]+)`),
  new RegExp(COMMENT_LEAD + String.raw`.*?\bgenerated\s+(?:by\s+\S+\s+)?from\s+["'\x60]?([^\s"'\x60,;]+)`, 'i'),
];


/** One command a config file runs, with the directory it runs in. */
interface ConfigEntry {
  command: string;
  cwd: string;
  configFile: string;
  evidence: string;
}

const MAX_GO_FILES_PER_DIR = 500;
const MAX_CONFIG_BYTES = 1024 * 1024;
const MAX_WORKFLOW_FILES = 200;
/** Entries kept per directory (and for the workflows): a bound on repository-controlled work. */
const MAX_ENTRIES_PER_SOURCE = 5_000;
/** Characters of one command that are parsed; a longer command is truncated, never scanned whole. */
const MAX_COMMAND_SCAN = 4_096;
const GO_GENERATE = '//go:generate';
// Go's flag package spells flags with one dash (`stringer -output=`, `mockgen -destination=`).
const OUTPUT_FLAGS = new Set(['-o', '--out', '--output', '--output-dir', '--out-dir', '--outdir', '--outDir', '--output-path', '-out', '-output', '-destination']);
const INPUT_FLAGS = new Set(['-i', '--input', '--input-spec', '--schema', '--spec', '-input', '-source']);

/** Split a shell line into simple commands and tokens. Quotes are honored; nothing is expanded. */
export function tokenizeCommand(command: string): string[][] {
  const commands: string[][] = [];
  let tokens: string[] = [];
  let cur = '';
  let quote: '"' | "'" | null = null;
  let has = false;
  const flushToken = () => { if (has) tokens.push(cur); cur = ''; has = false; };
  const flushCommand = () => { flushToken(); if (tokens.length) commands.push(tokens); tokens = []; };
  for (let i = 0; i < command.length; i++) {
    const c = command[i];
    if (quote) {
      if (c === quote) quote = null;
      else cur += c;
      continue;
    }
    if (c === '"' || c === "'") { quote = c; has = true; continue; }
    if (c === '\\') {
      // A backslash-newline continues the line; any other escaped character is taken literally.
      if (command[i + 1] === '\n') { i++; continue; }
      if (i + 1 < command.length) { cur += command[++i]; has = true; }
      continue;
    }
    if (c === '&' && command[i + 1] === '>') continue; // `&>` redirects like `>`
    if (c === '\n' || c === ';' || c === '|' || c === '&') { flushCommand(); continue; }
    // A subshell `( … )` is its own marker command, so a `cd` inside it is undone at `)`.
    if (c === '(' || c === ')') { flushCommand(); commands.push([c]); continue; }
    if (c === '>') {
      // `2>` names a file descriptor, not an argument.
      if (has && /^\d+$/.test(cur)) { cur = ''; has = false; } else flushToken();
      if (command[i + 1] === '>' || command[i + 1] === '|') i++;
      if (command[i + 1] === '&') {
        // `>&2`, `2>&1`: a descriptor duplication, not a file.
        i++;
        while (i + 1 < command.length && /[\d-]/.test(command[i + 1])) i++;
        continue;
      }
      tokens.push('>');
      continue;
    }
    if (/\s/.test(c)) { flushToken(); continue; }
    cur += c;
    has = true;
  }
  flushCommand();
  return commands;
}

/** Literal, non-expanding path tokens only: no globs, variables, or substitutions. */
function isLiteralPath(tok: string): boolean {
  return tok.length > 0 && !/[*?[\]{}$`~\\]/.test(tok) && !tok.includes('://');
}

/** The output paths and input candidates one simple command names. */
export function commandPaths(tokens: string[]): { outputs: string[]; inputs: string[] } {
  const outputs: string[] = [];
  const inputs: string[] = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (t === '>') { if (tokens[i + 1]) outputs.push(tokens[++i]); continue; }
    const eq = t.indexOf('=');
    const flag = t.startsWith('-') ? (eq > 0 ? t.slice(0, eq) : t) : null;
    const inline = flag && eq > 0 ? t.slice(eq + 1) : null;
    if (flag) {
      // protoc-style plugin output: `--go_out=gen`, `--ts_proto_out=opt=x:gen`.
      if (/^--[A-Za-z0-9-]+_out$/.test(flag)) {
        const value = inline ?? tokens[++i];
        // `opts:dir` — but a drive-letter path (`C:\\gen`) is kept whole and later refused.
        if (value) outputs.push(/^[A-Za-z]:[\\/]/.test(value) || !value.includes(':') ? value : value.slice(value.lastIndexOf(':') + 1));
      } else if (OUTPUT_FLAGS.has(flag)) {
        const value = inline ?? tokens[++i];
        if (value) outputs.push(value);
      } else if (INPUT_FLAGS.has(flag)) {
        const value = inline ?? tokens[++i];
        if (value) inputs.push(value);
      }
      continue;
    }
    if (i > 0) inputs.push(t);
  }
  return {
    outputs: outputs.filter(isLiteralPath),
    inputs: inputs.filter(isLiteralPath),
  };
}

/** `out` is root-relative; `''` is the root itself. */
function under(file: string, out: string): boolean {
  return out === '' || file === out || file.startsWith(out + '/');
}

class SourceResolver {
  private readonly fileCache = new Map<string, boolean>();
  private readonly entryCache = new Map<string, ConfigEntry[]>();
  private workflowEntries: ConfigEntry[] | null = null;
  /** Set when an entry cap was reached, so the result can say so. */
  capped = false;

  constructor(private readonly root: string) {}

  async isFile(rel: string): Promise<boolean> {
    const cached = this.fileCache.get(rel);
    if (cached !== undefined) return cached;
    let ok = false;
    const handle = await openConfined(this.root, rel);
    if (handle) {
      try { ok = (await handle.stat()).isFile(); } catch { ok = false; } finally { await handle.close().catch(() => undefined); }
    }
    this.fileCache.set(rel, ok);
    return ok;
  }

  private async readText(rel: string): Promise<string | null> {
    return readHead(this.root, rel, MAX_CONFIG_BYTES);
  }

  /** Root-relative path for `p` written relative to `cwd`; `''` is the root, null leaves it. */
  private rel(cwd: string, p: string): string | null {
    // An absolute path names nothing inside the repository the entry can be held to.
    if (p.startsWith('/') || /^[A-Za-z]:[\\/]/.test(p)) return null;
    const joined = posix.normalize(cwd === '' || cwd === '.' ? p : `${cwd}/${p}`).replace(/\/+$/, '');
    if (joined === '.' || joined === '') return '';
    return normalizeRel(joined);
  }

  async resolve(file: string, head: string | null): Promise<Pick<GeneratedFileFact, 'generatedFrom' | 'regenerateWith' | 'evidence' | 'configFile'>> {
    const evidence: string[] = [];
    const resolvedSources: string[] = [];
    const unresolvedSources: string[] = [];

    // 1. A header that names its source literally. Resolved against the file's directory, then the
    //    root; an unresolvable literal is still reported as written, never re-targeted by guesswork.
    if (head !== null) {
      const dir = posix.dirname(file);
      for (const lit of headerSources(head, file)) {
        const nearby = this.rel(dir, lit) || null;
        const fromRoot = normalizeRel(lit);
        const hit = nearby && await this.isFile(nearby) ? nearby
          : fromRoot && await this.isFile(fromRoot) ? fromRoot
          : null;
        if (hit) { if (!resolvedSources.includes(hit)) resolvedSources.push(hit); }
        else if (!unresolvedSources.includes(lit)) unresolvedSources.push(lit);
        evidence.push(hit ? `header names ${lit}` : `header names ${lit} (not found in the repository)`);
      }
    }

    // 2. A config-invoked entry that names this file (or a directory holding it) as its output.
    const match = await this.findEntry(file);
    let regenerateWith: string | 'unknown' = 'unknown';
    let configFile: string | undefined;
    if (match) {
      regenerateWith = match.entry.command;
      configFile = match.entry.configFile;
      evidence.push(match.entry.evidence);
    }

    // A header source that resolves wins; then the entry's inputs (a protoc header names its source
    // relative to the import path, which the entry's literal input path pins down); then the
    // header's literal as written.
    const generatedFrom = resolvedSources.length ? resolvedSources
      : match && match.inputs.length ? match.inputs
      : unresolvedSources;

    return {
      generatedFrom: generatedFrom.length ? generatedFrom : 'unknown',
      regenerateWith,
      ...(evidence.length ? { evidence } : {}),
      ...(configFile ? { configFile } : {}),
    };
  }

  private async findEntry(file: string): Promise<{ entry: ConfigEntry; inputs: string[] } | null> {
    const dirs: string[] = [];
    for (let d = posix.dirname(file); ; d = posix.dirname(d)) {
      dirs.push(d === '.' ? '' : d);
      if (d === '.' || d === '/' || d === '') break;
    }
    const sources = [...dirs.map(d => () => this.entriesIn(d)), () => this.workflows()];

    for (const load of sources) {
      for (const entry of await load()) {
        const hit = await this.matchEntry(entry, file);
        if (hit) return hit;
      }
    }
    return null;
  }

  /**
   * Whether one entry writes `file`. A literal `cd dir` moves the directory the following simple
   * commands run in; a `cd` to anything else ends the entry, since where it runs is then unknown.
   * An output that is the directory the command runs in (`--go_out=.`) claims everything below it,
   * so it names nothing and is skipped.
   */
  private async matchEntry(entry: ConfigEntry, file: string): Promise<{ entry: ConfigEntry; inputs: string[] } | null> {
    let cwd: string | null = entry.cwd;
    const subshells: string[] = [];
    for (const tokens of tokenizeCommand(entry.command)) {
      if (tokens.length === 1 && tokens[0] === '(') { subshells.push(cwd); continue; }
      if (tokens.length === 1 && tokens[0] === ')') { cwd = subshells.pop() ?? entry.cwd; continue; }
      if (tokens[0] === 'cd' || tokens[0] === 'pushd') {
        cwd = tokens.length === 2 && tokens[1] !== '-' && isLiteralPath(tokens[1]) ? this.rel(cwd, tokens[1]) : null;
        if (cwd === null) return null;
        continue;
      }
      const here = cwd;
      const { outputs, inputs } = commandPaths(tokens);
      // An output that is the command's own directory, or above it, claims every file below it.
      const outs = outputs.map(o => this.rel(here, o)).filter((o): o is string => o !== null && !under(here, o));
      if (!outs.some(o => under(file, o))) continue;
      const real: string[] = [];
      for (const raw of inputs) {
        const p = this.rel(here, raw);
        if (!p || p === file || outs.some(o => under(p, o))) continue;
        if (await this.isFile(p) && !real.includes(p)) real.push(p);
      }
      return { entry, inputs: real };
    }
    return null;
  }

  /** go-generate directives, package.json scripts, and Makefile recipes in one directory. */
  private async entriesIn(dir: string): Promise<ConfigEntry[]> {
    const cached = this.entryCache.get(dir);
    if (cached) return cached;
    const entries: ConfigEntry[] = [];
    const add = (e: ConfigEntry) => { if (entries.length < MAX_ENTRIES_PER_SOURCE) entries.push(e); else this.capped = true; };
    const join = (name: string) => (dir ? `${dir}/${name}` : name);

    let names: string[];
    try {
      names = (await readdir(safeJoin(this.root, dir || '.'))).sort();
    } catch { names = []; }

    // go-generate directives: they run in the directory of the file that holds them.
    for (const name of names.filter(n => n.endsWith('.go')).slice(0, MAX_GO_FILES_PER_DIR)) {
      const text = await this.readText(join(name));
      if (!text || !text.includes('//go:generate')) continue;
      text.split('\n').forEach((raw, idx) => {
        // Prefix test and trim, no regex: a directive line is repository content of any length.
        if (!raw.startsWith(GO_GENERATE) || !/\s/.test(raw.charAt(GO_GENERATE.length))) return;
        const cmd = raw.slice(GO_GENERATE.length, GO_GENERATE.length + MAX_COMMAND_SCAN).trim();
        if (cmd) add({ command: cmd, cwd: dir, configFile: join(name), evidence: `go:generate in ${join(name)}:${idx + 1}` });
      });
    }

    if (names.includes('package.json')) {
      const text = await this.readText(join('package.json'));
      try {
        const scripts = text ? (JSON.parse(text) as { scripts?: unknown }).scripts : undefined;
        if (scripts && typeof scripts === 'object' && !Array.isArray(scripts)) {
          for (const [name, body] of Object.entries(scripts).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
            if (typeof body === 'string') {
              add({ command: body.slice(0, MAX_COMMAND_SCAN), cwd: dir, configFile: join('package.json'), evidence: `package.json script "${name}" in ${join('package.json')}` });
            }
          }
        }
      } catch { /* unparseable manifest: no entries */ }
    }

    for (const mk of ['GNUmakefile', 'Makefile', 'makefile']) {
      if (!names.includes(mk)) continue;
      const text = await this.readText(join(mk));
      if (text) for (const r of makefileRecipes(text)) add({ command: r.command, cwd: dir, configFile: join(mk), evidence: `Makefile target "${r.target}" in ${join(mk)}:${r.line}` });
      break;
    }

    this.entryCache.set(dir, entries);
    return entries;
  }

  /** CI run steps from `.github/workflows/*.yml` at the analyzed root. */
  private async workflows(): Promise<ConfigEntry[]> {
    if (this.workflowEntries) return this.workflowEntries;
    const entries: ConfigEntry[] = [];
    const wfDir = '.github/workflows';
    let names: string[];
    try { names = (await readdir(safeJoin(this.root, wfDir))).filter(n => /\.ya?ml$/.test(n)).sort().slice(0, MAX_WORKFLOW_FILES); } catch { names = []; }
    for (const name of names) {
      const rel = `${wfDir}/${name}`;
      const text = await this.readText(rel);
      if (!text) continue;
      let doc: unknown;
      try { doc = parseYaml(text); } catch { continue; }
      const jobs = (doc as { jobs?: unknown } | null)?.jobs;
      if (!jobs || typeof jobs !== 'object') continue;
      const workflowDefault = runWorkingDirectory(doc);
      for (const [jobId, job] of Object.entries(jobs as Record<string, unknown>)) {
        const steps = (job as { steps?: unknown })?.steps;
        if (!Array.isArray(steps)) continue;
        const jobDefault = runWorkingDirectory(job) ?? workflowDefault;
        steps.forEach((step, idx) => {
          const run = (step as { run?: unknown })?.run;
          if (typeof run !== 'string') return;
          // step `working-directory`, else the job's `defaults.run`, else the workflow's.
          const wd = (step as { 'working-directory'?: unknown })?.['working-directory'] ?? jobDefault;
          let cwd = '';
          if (wd !== undefined) {
            // A computed directory (`${{ matrix.dir }}`) is unknown: the step names nothing.
            if (typeof wd !== 'string' || !isLiteralPath(wd)) return;
            const norm = posix.normalize(wd).replace(/\/+$/, '');
            if (norm !== '.' && norm !== '') {
              const r = normalizeRel(norm);
              if (r === null || norm.startsWith('/')) return;
              cwd = r;
            }
          }
          if (entries.length >= MAX_ENTRIES_PER_SOURCE) { this.capped = true; return; }
          entries.push({ command: run.slice(0, MAX_COMMAND_SCAN).trim(), cwd, configFile: rel, evidence: `CI run step ${jobId}#${idx + 1} in ${rel}` });
        });
      }
    }
    this.workflowEntries = entries;
    return entries;
  }
}

/** `defaults.run.working-directory` of a workflow or job; undefined when not set. */
function runWorkingDirectory(node: unknown): unknown {
  const defaults = (node as { defaults?: { run?: Record<string, unknown> } } | null)?.defaults;
  return defaults?.run?.['working-directory'];
}

/**
 * Recipes of a Makefile with backslash continuations joined. A rule line (`a b: deps`,
 * `%.pb.go: %.proto`) opens a target; a variable assignment (`X := y`, `X ?= y`) does not.
 */
export function makefileRecipes(text: string): Array<{ target: string; command: string; line: number }> {
  const out: Array<{ target: string; command: string; line: number }> = [];
  const lines = text.split('\n').map(l => l.replace(/\r$/, ''));
  let target: string | null = null;
  for (let i = 0; i < lines.length; i++) {
    let line = lines[i];
    const start = i + 1;
    while (line.endsWith('\\') && i + 1 < lines.length) line = line.slice(0, -1) + ' ' + lines[++i].replace(/^\t/, '');
    if (line.startsWith('\t')) {
      if (!target) continue;
      const cmd = line.slice(1).replace(/^[@+-]+/, '').trim();
      if (cmd) out.push({ target, command: cmd.slice(0, MAX_COMMAND_SCAN), line: start });
      continue;
    }
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    // A conditional may wrap recipe lines; it neither opens nor closes a target.
    if (/^\s*(?:ifeq|ifneq|ifdef|ifndef|else|endif)\b/.test(line)) continue;
    // Greedy and anchored, so linear on a long line: a rule is everything up to its first `:`.
    // `X := y` and `X ::= y` are assignments, not rules.
    const rule = /^([^\t#=:][^=:]*):(?!:?=)/.exec(line);
    target = rule && !/^\s*(?:export|override|define|include|-include)\b/.test(line)
      ? rule[1].trim().split(/\s+/)[0]
      : null;
  }
  return out;
}


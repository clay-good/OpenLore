/**
 * Generated-file guard (change: add-generated-file-guard).
 *
 * Agents hand-edit generated code, vendored code, and lockfiles. The edit is erased by the next
 * generator run, and the file the agent should have edited is one hop away and never shown. This
 * module answers two questions about a file, deterministically and offline:
 *
 *   1. Is it generated, vendored, or a lockfile — and by which rule? A closed, ordered rule set:
 *      a recognized header marker in the first lines, a `.gitattributes` linguist attribute, a
 *      lockfile name, then the existing excluded-path patterns. The first rule that matches wins
 *      and is recorded.
 *   2. Where is its source, and what command regenerates it? Only what a header or a
 *      config-invoked entry (a go-generate directive, a package.json script, a Makefile recipe, a
 *      CI run step) names LITERALLY. Anything else is `unknown` — never guessed.
 *
 * Consumers: `orient` and `blast_radius` mark generated files in scope; `verify_change` reports the
 * `generated-file-edited` finding; the loop hook surfaces (add-agent-loop-hook-surfaces) can call
 * {@link classifyGeneratedFiles} before a write. Nothing here runs a generator or blocks an edit.
 */


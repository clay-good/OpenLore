export type GeneratedRule = 'header-marker' | 'gitattributes' | 'lockfile' | 'path-pattern';

export interface GeneratedFileFact {
  /** Path relative to the analyzed root, forward slashes. */
  file: string;
  /** Which rule of the closed, ordered set matched first. */
  rule: GeneratedRule;
  /** What matched within that rule: a marker id, an attribute, a lockfile name, or a path pattern. */
  matched: string;
  kind: 'generated' | 'vendored' | 'lockfile';
  /** The source file(s), as named literally by a header or a config entry; else `unknown`. */
  generatedFrom: string[] | 'unknown';
  /** The literal command from the config entry that writes this file; else `unknown`. */
  regenerateWith: string | 'unknown';
  /** Where `generatedFrom` / `regenerateWith` were read, e.g. `go:generate in gen.go:3`. */
  evidence?: string[];
  /** The config file holding `regenerateWith` (editing it counts as editing the source side). */
  configFile?: string;
  /** A path-pattern match is weaker evidence than a marker, attribute, or lockfile name. */
  certainty: 'declared' | 'path-pattern';
}

export interface ClassifyResult {
  facts: Map<string, GeneratedFileFact>;
  /** Rules that could not run (e.g. not a git repository), so a quiet result is not read as "none". */
  boundaries: string[];
}


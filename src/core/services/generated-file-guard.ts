export interface ChangedPath {
  path: string;
  status: 'added' | 'modified' | 'deleted' | 'renamed';
  /** False for a pure rename (no lines added or removed); unset means the content changed. */
  contentChanged?: boolean;
}

const SOURCE = 'generated-file-guard';

function inChanged(changed: ReadonlySet<string>, literal: string): boolean {
  if (changed.has(literal)) return true;
  for (const c of changed) if (c.endsWith('/' + literal)) return true;
  return false;
}

/**
 * The `generated-file-edited` findings for one diff. Pure: `facts` comes from
 * {@link classifyGeneratedFiles} over the diff's files.
 *
 * Fires for a MODIFIED (or renamed) file only — a newly added generated file is what a generator
 * run produces, and a deleted one is not an edit. A generated file fires unless its known source,
 * or the config file holding its regenerate command, changed in the same diff; a file with an
 * unknown source fires with that said. A lockfile fires unless a manifest of its ecosystem at or
 * below its directory changed (a workspace member's manifest counts).
 */
export function generatedFileEditedFindings(
  changed: readonly ChangedPath[],
  facts: ReadonlyMap<string, GeneratedFileFact>,
): GovernanceFinding[] {
  const changedSet = new Set(changed.map(c => c.path));
  const findings: GovernanceFinding[] = [];
  for (const c of [...changed].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))) {
    if (c.status !== 'modified' && c.status !== 'renamed') continue;
    if (c.contentChanged === false) continue; // a move is not an edit
    const raw = facts.get(c.path);
    if (!raw) continue;
    // Matching reads the facts as given; the message carries only screened repository text.
    const fact = emittedFact(raw);

    if (fact.kind === 'lockfile') {
      const dir = posix.dirname(fact.file);
      const manifests = LOCKFILE_MANIFESTS[fact.matched] ?? [];
      const manifestChanged = [...changedSet].some(p =>
        manifests.includes(posix.basename(p)) && (dir === '.' || p.startsWith(dir + '/')));
      if (manifestChanged) continue;
      findings.push({
        code: 'generated-file-edited', severity: 'info', source: SOURCE, subject: fact.file,
        message: `Lockfile ${fact.file} changed without its manifest (${manifests.join(' or ')}) in the diff.`,
        location: { path: fact.file },
      });
      continue;
    }

    const rawSources = raw.generatedFrom === 'unknown' ? [] : raw.generatedFrom;
    const sourceChanged = rawSources.some(s => inChanged(changedSet, s))
      || (raw.configFile !== undefined && changedSet.has(raw.configFile));
    if (sourceChanged) continue;
    const sources = fact.generatedFrom === 'unknown' ? [] : fact.generatedFrom;

    const what = fact.kind === 'vendored' ? 'vendored' : 'generated';
    const by = `${fact.rule}: ${fact.matched}`;
    const from = sources.length ? `its source ${sources.join(', ')} is not in the diff` : 'its source is unknown';
    const regen = fact.regenerateWith !== 'unknown' ? `; regenerate with \`${fact.regenerateWith}\`` : '';
    findings.push({
      code: 'generated-file-edited',
      severity: fact.certainty === 'declared' ? 'warning' : 'info',
      source: SOURCE,
      subject: fact.file,
      message: `${fact.file} is ${what} (${by}${fact.certainty === 'path-pattern' ? ', path pattern only' : ''}) and was edited; ${from}${regen}.`,
      location: { path: fact.file },
    });
  }
  return findings;
}

export interface DiffGuardResult {
  /** Generated, vendored, and lockfile facts for the diff's files. */
  facts: GeneratedFileFact[];
  findings: GovernanceFinding[];
  boundaries: string[];
}

/**
 * Classify the files a diff touches (lockfiles included) and project the `generated-file-edited`
 * findings. Paths are re-framed from the repository root onto `root`; files outside `root` are
 * out of scope.
 */
export async function guardDiff(root: string, baseRef: string): Promise<DiffGuardResult> {
  const { getChangedFiles, getRepoPrefix, reframeRepoPath } = await import('../drift/git-diff.js');
  const diff = await getChangedFiles({ rootPath: root, baseRef, includeUnstaged: true, includeSkippable: true });
  const prefix = (await getRepoPrefix(root)) ?? '';
  const changed: ChangedPath[] = [];
  for (const f of diff.files) {
    const path = reframeRepoPath(f.path, prefix);
    if (path !== null) changed.push({ path, status: f.status, ...(f.status === 'renamed' ? { contentChanged: f.additions + f.deletions > 0 } : {}) });
  }
  // Findings match the diff against the raw facts (redaction must not rewrite a path it compares);
  // only screened facts leave this function.
  const { facts, boundaries } = await classifyGeneratedFiles(root, changed.filter(c => c.status !== 'deleted').map(c => c.path), { raw: true });
  return {
    facts: [...facts.values()].map(emittedFact),
    findings: generatedFileEditedFindings(changed, facts),
    boundaries,
  };
}

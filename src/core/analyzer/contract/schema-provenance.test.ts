/**
 * Schema provenance: the predicate itself, its bounds, and the guard it must stay in step with
 * (change: disclose-schema-provenance).
 */

import { describe, it, expect } from 'vitest';
import {
  schemaProvenance, schemaPathProvenance, matchSchemaHeaderMarker,
  GENERATED_SCHEMA_HEADER_MARKERS, SCHEMA_PROVENANCE_HEAD_BYTES,
} from './types.js';
import { GENERATED_HEADER_MARKERS, matchHeaderMarker } from '../../services/generated-file-guard.js';

/** Header shapes a schema file really carries, each with the marker id it must resolve to. */
const HEADERS: ReadonlyArray<[string, string | null]> = [
  ['# @generated\ntype Query { a: Int }\n', 'at-generated'],
  ['// @generated by protobuf-es\nsyntax = "proto3";\n', 'at-generated'],
  ['// Code generated by protoc-gen-go. DO NOT EDIT.\nsyntax = "proto3";\n', 'go-code-generated'],
  ['# AUTO-GENERATED FILE\ntype Query { a: Int }\n', 'auto-generated-banner'],
  ['# This file was automatically generated by graphql-codegen\ntype Query { a: Int }\n', 'auto-generated-banner'],
  ['# Generated schema -- DO NOT EDIT\ntype Query { a: Int }\n', 'generated-do-not-edit'],
  ['/* auto-generated by swagger-codegen */\nopenapi: 3.0.0\n', 'auto-generated-banner'],
  ['# The order service schema.\ntype Query { a: Int }\n', null],
  ['type Query { a: Int }\n# @generated\n', null],
  ['"""A generated-looking description, do not edit."""\ntype Query { a: Int }\n', null],
];

describe('schema provenance', () => {
  it('reads a declared generator header as `declared`, by the guard\'s marker ids', () => {
    for (const [head, id] of HEADERS) {
      expect(matchSchemaHeaderMarker(head)).toBe(id);
      const p = schemaProvenance('schema.graphql', head);
      if (id === null) expect(p).toBeNull();
      else expect(p).toEqual({ kind: 'generated', matched: id, certainty: 'declared' });
    }
  });

  it('reads a path pattern as `path-pattern`, never as `declared`', () => {
    const cases: Array<[string, { kind: string; matched: string } | null]> = [
      ['src/__generated__/schema.graphql', { kind: 'generated', matched: '__generated__/' }],
      ['app/generated/schema.graphql', { kind: 'generated', matched: 'generated/' }],
      ['api/schema.generated.graphql', { kind: 'generated', matched: '*.generated.*' }],
      ['vendor/acme/schema.graphql', { kind: 'vendored', matched: 'vendor/' }],
      ['third_party/acme/schema.proto', { kind: 'vendored', matched: 'third_party/' }],
      ['third-party/acme/schema.proto', { kind: 'vendored', matched: 'third_party/' }],
      ['node_modules/acme/schema.graphql', { kind: 'vendored', matched: 'node_modules/' }],
      ['api/schema.graphql', null],
      // `generated` must be a path SEGMENT: a hand-written file is not generated for naming one.
      ['api/generatedschema.graphql', null],
      // Case-insensitive: on a case-insensitive checkout `Vendor/` is `vendor/`.
      ['Vendor/acme/schema.graphql', { kind: 'vendored', matched: 'vendor/' }],
      ['src/__GENERATED__/schema.graphql', { kind: 'generated', matched: '__generated__/' }],
    ];
    for (const [path, want] of cases) {
      const p = schemaPathProvenance(path);
      if (want === null) expect(p, path).toBeNull();
      else expect(p, path).toEqual({ ...want, certainty: 'path-pattern' });
      // Windows separators resolve the same way.
      expect(schemaPathProvenance(path.split('/').join('\\'))).toEqual(p);
    }
  });

  it('a declared header wins over a path pattern, and neither ever drops a schema', () => {
    expect(schemaProvenance('vendor/a/schema.graphql', '# @generated\n'))
      .toEqual({ kind: 'generated', matched: 'at-generated', certainty: 'declared' });
    // No head in hand is not evidence of anything: the path still speaks, at its own certainty.
    expect(schemaProvenance('vendor/a/schema.graphql')).toEqual({ kind: 'vendored', matched: 'vendor/', certainty: 'path-pattern' });
    expect(schemaProvenance('api/schema.graphql', 'type Query { a: Int }\n')).toBeNull();
  });

  it('stays in step with the generated-file guard it borrows its vocabulary from', () => {
    const guardIds = GENERATED_HEADER_MARKERS.map(m => m.id);
    expect(GENERATED_SCHEMA_HEADER_MARKERS.map(m => m.id)).toEqual(guardIds);
    // Same verdict as the guard on every header shape, so the two cannot drift apart silently.
    for (const [head] of HEADERS) {
      expect(matchSchemaHeaderMarker(head), head.slice(0, 30)).toBe(matchHeaderMarker(head, 'schema.graphql'));
    }
  });

  it('reads only a bounded head, whatever the file size, and stays linear', () => {
    const marker = '# @generated\n';
    const filler = 'type T { a: Int }\n'.repeat(60_000); // ~1 MB
    // A marker past the bounded head is NOT detected: the scan never reads a 10 MB schema whole.
    const buried = filler.repeat(10) + marker;
    expect(buried.length).toBeGreaterThan(10 * 1024 * 1024);
    const t0 = process.hrtime.bigint();
    expect(schemaProvenance('api/schema.graphql', buried.slice(0, SCHEMA_PROVENANCE_HEAD_BYTES))).toBeNull();
    // Even handed the WHOLE text, the predicate slices its own head: cost does not grow with size.
    expect(schemaProvenance('api/schema.graphql', buried)).toBeNull();
    const big = Number(process.hrtime.bigint() - t0);
    const t1 = process.hrtime.bigint();
    schemaProvenance('api/schema.graphql', filler);
    const small = Number(process.hrtime.bigint() - t1);
    // Linear at worst: 10x the input must not cost 10x (the head bound makes it constant).
    expect(big).toBeLessThan(Math.max(small, 1) * 50 + 50_000_000);
    // A hostile path is scanned linearly too.
    const longPath = 'a/'.repeat(80_000) + 'schema.graphql';
    expect(longPath.length).toBeGreaterThan(128 * 1024);
    expect(schemaPathProvenance(longPath)).toBeNull();
    expect(schemaPathProvenance('vendor/' + longPath)).toEqual({ kind: 'vendored', matched: 'vendor/', certainty: 'path-pattern' });
  });
});
